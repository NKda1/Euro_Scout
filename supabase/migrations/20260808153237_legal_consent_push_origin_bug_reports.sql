-- Anonymous bug reports are inserted only through the rate-limited server action.
create table if not exists public.bug_reports (
  id bigint generated by default as identity primary key,
  message text not null check (char_length(message) between 1 and 4000),
  page_url text check (page_url is null or char_length(page_url) <= 2048),
  profile_id uuid references public.profiles(id) on delete set null,
  reporter_email text,
  user_agent text,
  created_at timestamptz not null default now()
);

alter table public.bug_reports enable row level security;
revoke all on table public.bug_reports from anon, authenticated;
revoke all on sequence public.bug_reports_id_seq from anon, authenticated;

create index if not exists bug_reports_created_at_idx
  on public.bug_reports (created_at desc);
create index if not exists bug_reports_profile_id_idx
  on public.bug_reports (profile_id)
  where profile_id is not null;
