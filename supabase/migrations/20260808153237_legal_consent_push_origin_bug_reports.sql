-- Versioned, explicit legal consent. Direct access stays service-role only.
create table if not exists public.legal_consents (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  email text,
  terms_version text not null,
  privacy_version text not null,
  source text not null check (source in ('email_signup', 'oauth_signup')),
  accepted_at timestamptz not null,
  created_at timestamptz not null default now(),
  unique (user_id, terms_version, privacy_version)
);

alter table public.legal_consents enable row level security;
revoke all on table public.legal_consents from anon, authenticated;
revoke all on sequence public.legal_consents_id_seq from anon, authenticated;

create index if not exists legal_consents_user_accepted_idx
  on public.legal_consents (user_id, accepted_at desc);

create schema if not exists private;

create or replace function private.record_signup_legal_consent()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if coalesce((new.raw_user_meta_data ->> 'legal_consent')::boolean, false) then
    insert into public.legal_consents (
      user_id,
      email,
      terms_version,
      privacy_version,
      source,
      accepted_at
    ) values (
      new.id,
      new.email,
      '2026-08-08',
      '2026-08-08',
      'email_signup',
      now()
    )
    on conflict (user_id, terms_version, privacy_version) do nothing;
  end if;

  return new;
end;
$$;

drop trigger if exists record_signup_legal_consent on auth.users;
create trigger record_signup_legal_consent
  after insert on auth.users
  for each row execute function private.record_signup_legal_consent();

